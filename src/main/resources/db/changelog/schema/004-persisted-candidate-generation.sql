CREATE TABLE generation_batch (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    generation_attempt_id   bigint NOT NULL REFERENCES generation_attempt(id) ON DELETE CASCADE,
    batch_number            smallint NOT NULL,
    batch_seed              bigint,
    status                  text NOT NULL,
    legacy_migrated         boolean NOT NULL DEFAULT false,
    fallback_level          text,
    reservoir_metrics       jsonb NOT NULL DEFAULT '{}'::jsonb,
    fallback_attempts       jsonb NOT NULL DEFAULT '[]'::jsonb,
    set_evaluation          jsonb,
    diagnostics             jsonb NOT NULL DEFAULT '[]'::jsonb,
    result_snapshot         jsonb,
    set_fingerprint         text,
    created_at              timestamptz NOT NULL DEFAULT now(),
    completed_at            timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT uq_generation_batch_number UNIQUE (generation_attempt_id, batch_number),
    CONSTRAINT ck_generation_batch_number CHECK (
        batch_number > 0 AND (legacy_migrated OR batch_number BETWEEN 1 AND 2)
    ),
    CONSTRAINT ck_generation_batch_status CHECK (status IN ('GENERATED', 'EXHAUSTED')),
    CONSTRAINT ck_generation_batch_result CHECK (
        legacy_migrated
        OR (
            status = 'GENERATED'
            AND batch_seed IS NOT NULL
            AND fallback_level IN ('STRICT', 'RELAXED_1', 'RELAXED_2')
            AND set_evaluation IS NOT NULL
            AND result_snapshot IS NOT NULL
            AND set_fingerprint ~ '^[0-9a-f]{64}$'
        )
        OR (
            status = 'EXHAUSTED'
            AND batch_seed IS NOT NULL
            AND fallback_level IS NULL
            AND set_evaluation IS NULL
            AND result_snapshot IS NOT NULL
            AND set_fingerprint IS NULL
        )
    )
);

