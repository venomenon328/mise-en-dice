-- Pre-9D in-flight attempts have neither a frozen context nor enough persisted input
-- to resume deterministically. Retain them as explicit technical failures instead of
-- silently regenerating them from current catalog state. Existing failures receive a
-- stable reason required by the new lifecycle.
UPDATE generation_attempt
SET status = 'FAILED',
    completed_at = COALESCE(completed_at, now()),
    failure_reason_code = 'CONTEXT_SNAPSHOT_INVALID',
    failure_detail = 'Legacy pending attempt has no replayable Phase-9D context snapshot'
WHERE status = 'PENDING';

UPDATE generation_attempt
SET failure_reason_code = 'TECHNICAL_GENERATION_FAILURE',
    failure_detail = COALESCE(failure_detail, 'Legacy technical generation failure')
WHERE status = 'FAILED' AND failure_reason_code IS NULL;

