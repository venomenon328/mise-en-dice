-- Every old curation round becomes a legacy batch. The explicit legacy marker is the
-- only exception to the new 1..2 production bound, preserving any previously legal
-- number of historical rounds without opening batch 3 for new attempts.
INSERT INTO generation_batch (
    generation_attempt_id,
    batch_number,
    status,
    legacy_migrated,
    diagnostics,
    created_at,
    completed_at
)
SELECT
    generation_attempt_id,
    row_number() OVER (PARTITION BY generation_attempt_id ORDER BY round_number, id),
    'GENERATED',
    true,
    '[]'::jsonb,
    created_at,
    COALESCE(completed_at, created_at)
FROM curation_round;

-- A pre-9D SUCCEEDED row without any curation round cannot satisfy the sharpened
-- meaning of GENERATED (at least one complete persisted batch).
UPDATE generation_attempt attempt
SET status = 'FAILED',
    failure_reason_code = 'CONTEXT_SNAPSHOT_INVALID',
    failure_detail = 'Legacy successful attempt has no persisted generation batch'
WHERE attempt.status = 'GENERATED'
  AND NOT EXISTS (
      SELECT 1 FROM generation_batch batch WHERE batch.generation_attempt_id = attempt.id
  );

