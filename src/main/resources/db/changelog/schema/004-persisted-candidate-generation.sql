-- Candidate ownership now follows candidate -> batch -> attempt. Manual references must
-- belong to that same attempt; a retained curation link is historical metadata only.
CREATE OR REPLACE FUNCTION validate_candidate_requirement_context()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    candidate_attempt_id bigint;
    manual_attempt_id bigint;
BEGIN
    SELECT batch.generation_attempt_id
      INTO candidate_attempt_id
      FROM challenge_candidate candidate
      JOIN generation_batch batch ON batch.id = candidate.generation_batch_id
     WHERE candidate.id = NEW.candidate_id;

    IF candidate_attempt_id IS NULL THEN
        RAISE EXCEPTION 'candidate % does not exist', NEW.candidate_id;
    END IF;

    IF NEW.source = 'MANUAL' THEN
        SELECT generation_attempt_id
          INTO manual_attempt_id
          FROM generation_manual_requirement
         WHERE id = NEW.manual_requirement_id;

        IF manual_attempt_id IS NULL THEN
            RAISE EXCEPTION 'manual requirement % does not exist', NEW.manual_requirement_id;
        END IF;

        IF manual_attempt_id <> candidate_attempt_id THEN
            RAISE EXCEPTION 'manual requirement % does not belong to candidate generation attempt %',
                NEW.manual_requirement_id, candidate_attempt_id;
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION validate_candidate_batch_context()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    batch_attempt_id bigint;
    batch_is_legacy boolean;
    round_attempt_id bigint;
BEGIN
    SELECT generation_attempt_id, legacy_migrated
      INTO batch_attempt_id, batch_is_legacy
      FROM generation_batch
     WHERE id = NEW.generation_batch_id;

    IF batch_attempt_id IS NULL THEN
        RAISE EXCEPTION 'generation batch % does not exist', NEW.generation_batch_id;
    END IF;

    IF NOT batch_is_legacy AND NEW.candidate_number NOT BETWEEN 1 AND 12 THEN
        RAISE EXCEPTION 'generated candidate number % must be between 1 and 12', NEW.candidate_number;
    END IF;

    IF NOT batch_is_legacy AND (
        NEW.curation_round_id IS NOT NULL
        OR NEW.is_selected IS NOT NULL
        OR NEW.curator_evaluation IS NOT NULL
    ) THEN
        RAISE EXCEPTION 'new generator candidate must not contain legacy curation state';
    END IF;

    IF NEW.curation_round_id IS NOT NULL THEN
        SELECT generation_attempt_id INTO round_attempt_id
        FROM curation_round WHERE id = NEW.curation_round_id;
        IF round_attempt_id IS DISTINCT FROM batch_attempt_id THEN
            RAISE EXCEPTION 'legacy curation round and generation batch must belong to the same attempt';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_candidate_validate_batch_context
BEFORE INSERT OR UPDATE OF generation_batch_id, curation_round_id, candidate_number, is_selected, curator_evaluation
ON challenge_candidate
FOR EACH ROW
EXECUTE FUNCTION validate_candidate_batch_context();

CREATE OR REPLACE FUNCTION assert_generation_batch_complete(target_batch_id bigint)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    batch_row generation_batch%ROWTYPE;
    candidate_count integer;
    incomplete_count integer;
BEGIN
    SELECT * INTO batch_row FROM generation_batch WHERE id = target_batch_id;
    IF NOT FOUND OR batch_row.legacy_migrated THEN
        RETURN;
    END IF;

    SELECT count(*) INTO candidate_count
    FROM challenge_candidate WHERE generation_batch_id = target_batch_id;

    IF batch_row.status = 'EXHAUSTED' THEN
        IF candidate_count <> 0 THEN
            RAISE EXCEPTION 'exhausted generation batch % must not contain candidates', target_batch_id;
        END IF;
        RETURN;
    END IF;

    IF candidate_count <> 12 THEN
        RAISE EXCEPTION 'generated batch % must contain exactly twelve candidates', target_batch_id;
    END IF;

    SELECT count(*) INTO incomplete_count
    FROM challenge_candidate candidate
    WHERE candidate.generation_batch_id = target_batch_id
      AND (
          candidate.candidate_number NOT BETWEEN 1 AND 12
          OR candidate.proposal_ordinal IS NULL
          OR candidate.profile IS NULL
          OR candidate.target_specificity IS NULL
          OR candidate.target_novelty_band IS NULL
          OR candidate.actual_novelty_band IS NULL
          OR candidate.known_novelty_load IS NULL
          OR candidate.total_score IS NULL
          OR candidate.data_confidence IS NULL
          OR candidate.component_scores IS NULL
          OR candidate.profile_slot_assignments IS NULL
          OR candidate.generator_reason_codes IS NULL
          OR candidate.generator_diagnostics IS NULL
          OR candidate.canonical_signature IS NULL
          OR (SELECT count(*) FROM candidate_requirement requirement
              WHERE requirement.candidate_id = candidate.id) <> 4
      );

    IF incomplete_count <> 0 THEN
        RAISE EXCEPTION 'generated batch % contains incomplete candidate snapshots', target_batch_id;
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION validate_generation_batch_complete_trigger()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    PERFORM assert_generation_batch_complete(CASE WHEN TG_OP = 'DELETE' THEN OLD.id ELSE NEW.id END);
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER trg_generation_batch_complete
AFTER INSERT OR UPDATE ON generation_batch
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION validate_generation_batch_complete_trigger();

CREATE OR REPLACE FUNCTION validate_candidate_batch_complete_trigger()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'DELETE' OR TG_OP = 'UPDATE' THEN
        PERFORM assert_generation_batch_complete(OLD.generation_batch_id);
    END IF;
    IF TG_OP = 'INSERT' OR TG_OP = 'UPDATE' THEN
        PERFORM assert_generation_batch_complete(NEW.generation_batch_id);
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER trg_candidate_batch_complete
AFTER INSERT OR UPDATE OR DELETE ON challenge_candidate
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION validate_candidate_batch_complete_trigger();

CREATE OR REPLACE FUNCTION validate_requirement_batch_complete_trigger()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    affected_batch_id bigint;
BEGIN
    SELECT generation_batch_id INTO affected_batch_id
    FROM challenge_candidate
    WHERE id = CASE WHEN TG_OP = 'DELETE' THEN OLD.candidate_id ELSE NEW.candidate_id END;
    IF affected_batch_id IS NOT NULL THEN
        PERFORM assert_generation_batch_complete(affected_batch_id);
    END IF;
    RETURN NULL;
END;
$$;

