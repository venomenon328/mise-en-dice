SET generation_batch_id = batch.id
FROM curation_round round_row
JOIN generation_batch batch
  ON batch.generation_attempt_id = round_row.generation_attempt_id
 AND batch.batch_number = (
     SELECT ranked.batch_number
     FROM (
         SELECT id, row_number() OVER (
             PARTITION BY generation_attempt_id ORDER BY round_number, id
         ) AS batch_number
         FROM curation_round
     ) ranked
     WHERE ranked.id = round_row.id
 )
WHERE candidate.curation_round_id = round_row.id;

