CREATE OR REPLACE FUNCTION validate_reroll_generation_attempt()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.attempt_type = 'REROLL' AND NOT EXISTS (
        SELECT 1 FROM reroll_offer_exposure WHERE challenge_session_id = NEW.challenge_session_id
    ) THEN
        RAISE EXCEPTION 'reroll generation attempt requires a committed rerolled offer exposure';
    END IF;
    RETURN NEW;
END;
$$;

