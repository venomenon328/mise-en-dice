CREATE OR REPLACE FUNCTION validate_reroll_offer_exposure_requirement()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    exposure_offer_set_id bigint;
    offer_candidate_id bigint;
    actual_source text;
    actual_concept_id bigint;
    actual_code text;
    actual_display text;
BEGIN
    SELECT curated_offer_set_id INTO exposure_offer_set_id
      FROM reroll_offer_exposure WHERE id = NEW.reroll_offer_exposure_id;
    SELECT challenge_candidate_id INTO offer_candidate_id
      FROM curated_offer
     WHERE id = NEW.curated_offer_id AND curated_offer_set_id = exposure_offer_set_id;
    IF offer_candidate_id IS NULL OR offer_candidate_id <> NEW.challenge_candidate_id THEN
        RAISE EXCEPTION 'reroll exposure requirement must reference an offer candidate of its exposed set';
    END IF;

    SELECT source, ingredient_concept_id, concept_code_snapshot, display_text_snapshot
      INTO actual_source, actual_concept_id, actual_code, actual_display
      FROM candidate_requirement
     WHERE candidate_id = NEW.challenge_candidate_id AND position = NEW.requirement_position;
    IF actual_source IS NULL OR actual_source <> NEW.source
       OR actual_concept_id IS DISTINCT FROM NEW.ingredient_concept_id
       OR actual_code IS DISTINCT FROM NEW.concept_code_snapshot
       OR actual_display IS DISTINCT FROM NEW.display_text_snapshot THEN
        RAISE EXCEPTION 'reroll exposure requirement must copy the authoritative candidate snapshot exactly';
    END IF;
    RETURN NEW;
END;
$$;

