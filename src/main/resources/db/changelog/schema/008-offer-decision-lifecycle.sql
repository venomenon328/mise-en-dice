CREATE OR REPLACE FUNCTION validate_curated_offer_decision_trigger()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    target_offer_set_id bigint;
BEGIN
    IF TG_TABLE_NAME = 'curated_offer_set' THEN
        target_offer_set_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.id ELSE NEW.id END;
    ELSIF TG_TABLE_NAME = 'reroll_offer_exposure' THEN
        target_offer_set_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.curated_offer_set_id ELSE NEW.curated_offer_set_id END;
    ELSIF TG_OP = 'DELETE' THEN
        IF OLD.curated_offer_id IS NULL THEN RETURN NULL; END IF;
        SELECT curated_offer_set_id INTO target_offer_set_id FROM curated_offer WHERE id = OLD.curated_offer_id;
    ELSIF NEW.curated_offer_id IS NULL THEN
        RETURN NULL;
    ELSE
        SELECT curated_offer_set_id INTO target_offer_set_id FROM curated_offer WHERE id = NEW.curated_offer_id;
    END IF;
    IF target_offer_set_id IS NOT NULL THEN
        PERFORM assert_curated_offer_decision(target_offer_set_id);
    END IF;
    RETURN NULL;
END;
$$;

