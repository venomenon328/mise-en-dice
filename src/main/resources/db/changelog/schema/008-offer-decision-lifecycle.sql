BEFORE INSERT OR UPDATE
ON reroll_offer_exposure_requirement
FOR EACH ROW
EXECUTE FUNCTION validate_reroll_offer_exposure_requirement();

CREATE OR REPLACE FUNCTION assert_reroll_offer_exposure_complete(target_exposure_id bigint)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    target_offer_set_id bigint;
    expected_count integer;
    actual_count integer;
BEGIN
    SELECT curated_offer_set_id INTO target_offer_set_id
      FROM reroll_offer_exposure WHERE id = target_exposure_id;
    IF NOT FOUND THEN
        RETURN;
    END IF;
    SELECT count(*) * 4 INTO expected_count FROM curated_offer WHERE curated_offer_set_id = target_offer_set_id;
    SELECT count(*) INTO actual_count
      FROM reroll_offer_exposure_requirement WHERE reroll_offer_exposure_id = target_exposure_id;
    IF expected_count = 0 OR actual_count <> expected_count THEN
        RAISE EXCEPTION 'reroll exposure % must contain exactly the four snapshots of every exposed offer',
            target_exposure_id;
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION validate_reroll_offer_exposure_complete_trigger()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    PERFORM assert_reroll_offer_exposure_complete(CASE WHEN TG_OP = 'DELETE' THEN OLD.id ELSE NEW.id END);
    RETURN NULL;
END;
$$;

