CREATE OR REPLACE FUNCTION validate_challenge_selected_candidate()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    candidate_attempt_id bigint;
    offer_attempt_id bigint;
    offer_candidate_id bigint;
    offer_set_status text;
BEGIN
    IF TG_OP = 'INSERT' AND NEW.legacy_pre_offer_decision THEN
        RAISE EXCEPTION 'legacy challenge marker is reserved for rows present before migration 008';
    ELSIF TG_OP = 'UPDATE'
          AND NEW.legacy_pre_offer_decision IS DISTINCT FROM OLD.legacy_pre_offer_decision THEN
        RAISE EXCEPTION 'legacy challenge marker is immutable';
    END IF;

    SELECT batch.generation_attempt_id
      INTO candidate_attempt_id
      FROM challenge_candidate candidate
      JOIN generation_batch batch ON batch.id = candidate.generation_batch_id
     WHERE candidate.id = NEW.selected_candidate_id;

    IF candidate_attempt_id IS NULL THEN
        RAISE EXCEPTION 'selected challenge candidate % does not exist', NEW.selected_candidate_id;
    END IF;
    IF candidate_attempt_id <> NEW.generation_attempt_id THEN
        RAISE EXCEPTION 'selected candidate % does not belong to generation attempt %',
            NEW.selected_candidate_id, NEW.generation_attempt_id;
    END IF;
    IF (SELECT count(*) FROM candidate_requirement WHERE candidate_id = NEW.selected_candidate_id) <> 4 THEN
        RAISE EXCEPTION 'selected candidate % must contain exactly four requirements', NEW.selected_candidate_id;
    END IF;

    IF NEW.curated_offer_id IS NULL THEN
        IF NEW.legacy_pre_offer_decision IS DISTINCT FROM true THEN
            RAISE EXCEPTION 'new challenges require a confirmed curated offer; only pre-migration legacy rows remain valid';
        END IF;
        RETURN NEW;
    END IF;

    IF NEW.legacy_pre_offer_decision THEN
        RAISE EXCEPTION 'legacy challenge marker cannot accompany a curated offer';
    END IF;

    SELECT offer_set.generation_attempt_id, offer.challenge_candidate_id, offer_set.status
      INTO offer_attempt_id, offer_candidate_id, offer_set_status
      FROM curated_offer offer
      JOIN curated_offer_set offer_set ON offer_set.id = offer.curated_offer_set_id
     WHERE offer.id = NEW.curated_offer_id;
    IF offer_attempt_id IS NULL OR offer_attempt_id <> NEW.generation_attempt_id
       OR offer_candidate_id <> NEW.selected_candidate_id OR offer_set_status <> 'CONFIRMED' THEN
        RAISE EXCEPTION 'new challenge must reference its confirmed offer and authoritative candidate';
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION assert_curated_offer_decision(target_offer_set_id bigint)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    target_status text;
    challenges_for_set integer;
    exposures_for_set integer;
BEGIN
    SELECT status INTO target_status FROM curated_offer_set WHERE id = target_offer_set_id;
    IF NOT FOUND THEN
        RETURN;
    END IF;
    SELECT count(*) INTO challenges_for_set
      FROM challenge challenge_row
      JOIN curated_offer offer ON offer.id = challenge_row.curated_offer_id
     WHERE offer.curated_offer_set_id = target_offer_set_id;
    SELECT count(*) INTO exposures_for_set
      FROM reroll_offer_exposure WHERE curated_offer_set_id = target_offer_set_id;
    IF target_status = 'CONFIRMED' AND (challenges_for_set <> 1 OR exposures_for_set <> 0) THEN
        RAISE EXCEPTION 'a confirmed offer set requires exactly one challenge and no reroll exposure';
    ELSIF target_status = 'REROLLED' AND (challenges_for_set <> 0 OR exposures_for_set <> 1) THEN
        RAISE EXCEPTION 'a rerolled offer set requires exactly one reroll exposure and no challenge';
    ELSIF target_status NOT IN ('CONFIRMED', 'REROLLED')
          AND (challenges_for_set <> 0 OR exposures_for_set <> 0) THEN
        RAISE EXCEPTION 'only terminal offer decisions may own a challenge or reroll exposure';
    END IF;
END;
$$;

