CREATE OR REPLACE FUNCTION assert_reroll_attempt_input(target_attempt_id bigint)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    target_session_id bigint;
    target_type text;
    target_date date;
    initial_attempt_id bigint;
    initial_date date;
    target_manuals jsonb;
    initial_manuals jsonb;
BEGIN
    SELECT challenge_session_id, attempt_type, effective_date
      INTO target_session_id, target_type, target_date
      FROM generation_attempt WHERE id = target_attempt_id;
    IF NOT FOUND OR target_type <> 'REROLL' THEN
        RETURN;
    END IF;
    SELECT id, effective_date INTO initial_attempt_id, initial_date
      FROM generation_attempt
     WHERE challenge_session_id = target_session_id AND attempt_type = 'INITIAL';
    IF initial_attempt_id IS NULL OR target_date IS DISTINCT FROM initial_date THEN
        RAISE EXCEPTION 'reroll generation input must retain the initial effective date';
    END IF;
    SELECT coalesce(jsonb_agg(jsonb_build_array(position, display_text, matched_ingredient_concept_id)
                     ORDER BY position), '[]'::jsonb)
      INTO target_manuals FROM generation_manual_requirement WHERE generation_attempt_id = target_attempt_id;
    SELECT coalesce(jsonb_agg(jsonb_build_array(position, display_text, matched_ingredient_concept_id)
                     ORDER BY position), '[]'::jsonb)
      INTO initial_manuals FROM generation_manual_requirement WHERE generation_attempt_id = initial_attempt_id;
    IF target_manuals <> initial_manuals THEN
        RAISE EXCEPTION 'reroll generation input must retain the initial manual requirements';
    END IF;
END;
$$;

