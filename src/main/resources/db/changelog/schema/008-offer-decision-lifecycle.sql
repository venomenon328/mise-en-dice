-- Phase 11A: transport-neutral presentation, decision, and reroll exposure lifecycle.
-- Existing challenges and legacy curation data stay readable.  New challenges are
-- authoritative only through curated_offer; legacy is_selected is never revived.

ALTER TABLE challenge
    ADD COLUMN curated_offer_id bigint REFERENCES curated_offer(id) ON DELETE RESTRICT,
    ADD CONSTRAINT uq_challenge_curated_offer UNIQUE (curated_offer_id);

-- This snapshot is intentionally taken while 008 runs: only rows that already existed
-- before the offer-decision schema may remain without the new authoritative reference.
-- A legacy-looking candidate batch is not sufficient authority for a later INSERT.
ALTER TABLE challenge
    ADD COLUMN legacy_pre_offer_decision boolean NOT NULL DEFAULT false;

UPDATE challenge
   SET legacy_pre_offer_decision = true
 WHERE curated_offer_id IS NULL;

ALTER TABLE challenge
    ADD CONSTRAINT ck_challenge_offer_authority
    CHECK (curated_offer_id IS NOT NULL OR legacy_pre_offer_decision);

CREATE TABLE reroll_offer_exposure (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_session_id    bigint NOT NULL UNIQUE REFERENCES challenge_session(id) ON DELETE RESTRICT,
    curated_offer_set_id    bigint NOT NULL UNIQUE REFERENCES curated_offer_set(id) ON DELETE RESTRICT,
    exposed_at              timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE reroll_offer_exposure_requirement (
    reroll_offer_exposure_id    bigint NOT NULL REFERENCES reroll_offer_exposure(id) ON DELETE CASCADE,
    curated_offer_id            bigint NOT NULL REFERENCES curated_offer(id) ON DELETE RESTRICT,
    challenge_candidate_id      bigint NOT NULL REFERENCES challenge_candidate(id) ON DELETE RESTRICT,
    requirement_position        smallint NOT NULL,
    source                      text NOT NULL,
    ingredient_concept_id       bigint REFERENCES ingredient_concept(id) ON DELETE RESTRICT,
    concept_code_snapshot       text,
    display_text_snapshot       text NOT NULL,

    PRIMARY KEY (reroll_offer_exposure_id, curated_offer_id, requirement_position),
    CONSTRAINT ck_reroll_offer_exposure_requirement_position CHECK (requirement_position BETWEEN 1 AND 4),
    CONSTRAINT ck_reroll_offer_exposure_requirement_source CHECK (source IN ('RANDOM', 'MANUAL')),
    CONSTRAINT ck_reroll_offer_exposure_requirement_display CHECK (btrim(display_text_snapshot) <> '')
);

CREATE INDEX ix_reroll_offer_exposure_set ON reroll_offer_exposure (curated_offer_set_id);
CREATE INDEX ix_reroll_offer_exposure_requirement_code
    ON reroll_offer_exposure_requirement (concept_code_snapshot)
    WHERE concept_code_snapshot IS NOT NULL;

CREATE OR REPLACE FUNCTION validate_curated_offer_set_decision_transition()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'CURATED_UNPRESENTED' OR NEW.presented_at IS NOT NULL OR NEW.decided_at IS NOT NULL THEN
            RAISE EXCEPTION 'new curated offer sets must start unpresented';
        END IF;
        RETURN NEW;
    END IF;

    IF OLD.status = 'CURATED_UNPRESENTED' THEN
        IF NEW.status <> 'PRESENTED_PENDING_DECISION'
           OR NEW.presented_at IS NULL OR NEW.decided_at IS NOT NULL THEN
            RAISE EXCEPTION 'an unpresented offer set may only become presented pending decision';
        END IF;
    ELSIF OLD.status = 'PRESENTED_PENDING_DECISION' THEN
        IF NEW.status NOT IN ('CONFIRMED', 'REROLLED')
           OR NEW.presented_at IS DISTINCT FROM OLD.presented_at OR NEW.decided_at IS NULL THEN
            RAISE EXCEPTION 'a presented offer set must receive exactly one terminal decision';
        END IF;
    ELSIF NEW.status IS DISTINCT FROM OLD.status
          OR NEW.presented_at IS DISTINCT FROM OLD.presented_at
          OR NEW.decided_at IS DISTINCT FROM OLD.decided_at THEN
        RAISE EXCEPTION 'terminal curated offer decisions are immutable';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_curated_offer_set_decision_transition
BEFORE INSERT OR UPDATE OF status, presented_at, decided_at
ON curated_offer_set
FOR EACH ROW
EXECUTE FUNCTION validate_curated_offer_set_decision_transition();

CREATE OR REPLACE FUNCTION validate_reroll_offer_exposure()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    offer_session_id bigint;
    offer_status text;
BEGIN
    SELECT attempt.challenge_session_id, offer_set.status
      INTO offer_session_id, offer_status
      FROM curated_offer_set offer_set
      JOIN generation_attempt attempt ON attempt.id = offer_set.generation_attempt_id
     WHERE offer_set.id = NEW.curated_offer_set_id;

    IF offer_session_id IS NULL OR offer_session_id <> NEW.challenge_session_id
       OR offer_status <> 'REROLLED' THEN
        RAISE EXCEPTION 'reroll exposure must belong to its rerolled presented offer set and session';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_reroll_offer_exposure_validate
BEFORE INSERT OR UPDATE OF challenge_session_id, curated_offer_set_id
ON reroll_offer_exposure
FOR EACH ROW
EXECUTE FUNCTION validate_reroll_offer_exposure();

