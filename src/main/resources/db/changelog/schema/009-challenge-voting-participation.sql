-- Once Phase 11B has snapshotted an electorate, a terminal 11A decision must be the result
-- materialized by this core. This prevents a stale direct confirm/reroll interaction from
-- bypassing an open or completed voting round while preserving the pre-11B 11A API path.
CREATE OR REPLACE FUNCTION assert_selection_authorized_offer_decision(target_offer_set_id bigint)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    target_status text;
    target_session_id bigint;
    target_offer_count integer;
    target_challenge_offer_id bigint;
    own_round record;
    source_round record;
BEGIN
    SELECT offer_set.status, attempt.challenge_session_id, offer_set.requested_offer_count
      INTO target_status, target_session_id, target_offer_count
      FROM curated_offer_set offer_set
      JOIN generation_attempt attempt ON attempt.id = offer_set.generation_attempt_id
     WHERE offer_set.id = target_offer_set_id;
    IF NOT FOUND OR target_status NOT IN ('CONFIRMED', 'REROLLED') THEN
        RETURN;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM selection_electorate WHERE challenge_session_id = target_session_id) THEN
        RETURN;
    END IF;

    SELECT * INTO own_round
      FROM selection_voting_round
     WHERE curated_offer_set_id = target_offer_set_id;
    IF FOUND THEN
        IF own_round.status <> 'COMPLETED' THEN
            RAISE EXCEPTION 'a presented offer set with an electorate requires a completed voting round decision';
        END IF;
        IF target_status = 'REROLLED' THEN
            IF own_round.result_option_type <> 'REROLL' THEN
                RAISE EXCEPTION 'only a persisted REROLL voting result may reroll its offer set';
            END IF;
            RETURN;
        END IF;
        SELECT curated_offer_id INTO target_challenge_offer_id
          FROM challenge
         WHERE curated_offer_id IN (SELECT id FROM curated_offer WHERE curated_offer_set_id = target_offer_set_id);
        IF own_round.result_option_type = 'OFFER'
           AND own_round.result_curated_offer_id = target_challenge_offer_id THEN
            RETURN;
        END IF;
        IF own_round.result_option_type = 'ACCEPT' AND own_round.round_number = 1 AND target_offer_count = 1 THEN
            RETURN;
        END IF;
        RAISE EXCEPTION 'only the persisted winning offer or ACCEPT result may confirm its offer set';
    END IF;

    SELECT * INTO source_round
      FROM selection_voting_round
     WHERE resulting_offer_set_id = target_offer_set_id
       AND result_option_type = 'REROLL'
     ORDER BY round_number DESC
     LIMIT 1;
    IF target_status = 'CONFIRMED' AND FOUND
       AND source_round.apply_state IN ('REROLL_AUTO_CONFIRM_PENDING', 'REROLL_AUTO_CONFIRMED')
       AND target_offer_count = 1 THEN
        RETURN;
    END IF;
    RAISE EXCEPTION 'an electorate session offer decision must be authorized by the voting core';
END;
$$;

CREATE OR REPLACE FUNCTION validate_selection_authorized_offer_decision_trigger()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    target_offer_set_id bigint;
BEGIN
    IF TG_TABLE_NAME = 'curated_offer_set' THEN
        target_offer_set_id := NEW.id;
    ELSE
        SELECT curated_offer_set_id INTO target_offer_set_id
          FROM curated_offer WHERE id = NEW.curated_offer_id;
    END IF;
    PERFORM assert_selection_authorized_offer_decision(target_offer_set_id);
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER trg_selection_offer_set_decision_authorized
AFTER INSERT OR UPDATE ON curated_offer_set
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION validate_selection_authorized_offer_decision_trigger();

CREATE CONSTRAINT TRIGGER trg_selection_challenge_decision_authorized
AFTER INSERT OR UPDATE ON challenge
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION validate_selection_authorized_offer_decision_trigger();
