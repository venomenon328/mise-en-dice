-- Phase 15A: durable, transport-neutral Challenge results, their one optional
-- result photo, and the explicit Challenge completion state. Results intentionally
-- refer directly to Challenge and participant; challenge_participation remains
-- non-authoritative legacy data.

ALTER TABLE challenge
    ADD COLUMN completed_at timestamptz;

-- Earlier schema versions recorded a COMPLETED status but no completion instant.
-- The original instant cannot be reconstructed. For the upgrade we use the already
-- durable shown_at as a deterministic compatibility timestamp, rather than leaving
-- a status/time combination that new readers cannot interpret consistently.
UPDATE challenge
   SET completed_at = shown_at
 WHERE status = 'COMPLETED';

-- The backfill updates historical challenge rows.  Flush any deferred FK events before the
-- subsequent ALTER TABLE; PostgreSQL otherwise rejects schema changes in that transaction.
SET CONSTRAINTS ALL IMMEDIATE;

ALTER TABLE challenge
    ADD CONSTRAINT ck_challenge_completion_timestamp
    CHECK ((status = 'COMPLETED') = (completed_at IS NOT NULL));

CREATE OR REPLACE FUNCTION validate_challenge_completion_transition()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.status = 'ACTIVE' THEN
        IF NEW.status = 'ACTIVE' AND NEW.completed_at IS NULL THEN
            RETURN NEW;
        END IF;
        IF NEW.status = 'COMPLETED' AND NEW.completed_at IS NOT NULL THEN
            RETURN NEW;
        END IF;
        RAISE EXCEPTION 'an active challenge may only remain active or be completed';
    END IF;

    IF OLD.status = 'COMPLETED' THEN
        IF NEW.status = 'COMPLETED' AND NEW.completed_at IS NOT DISTINCT FROM OLD.completed_at THEN
            RETURN NEW;
        END IF;
        RAISE EXCEPTION 'a completed challenge cannot be reopened or completed again with another timestamp';
    END IF;

    IF NEW.status IS DISTINCT FROM OLD.status OR NEW.completed_at IS DISTINCT FROM OLD.completed_at THEN
        RAISE EXCEPTION 'non-active challenge completion state is immutable';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_challenge_completion_transition
BEFORE UPDATE OF status, completed_at
ON challenge
FOR EACH ROW
EXECUTE FUNCTION validate_challenge_completion_transition();

CREATE TABLE challenge_result (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_id    bigint NOT NULL REFERENCES challenge(id) ON DELETE RESTRICT,
    participant_id  bigint NOT NULL REFERENCES participant(id) ON DELETE RESTRICT,
    dish_name       text NOT NULL,
    description     text NOT NULL,
    evaluation      text,
    version         bigint NOT NULL DEFAULT 0,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT uq_challenge_result_challenge_participant UNIQUE (challenge_id, participant_id),
    CONSTRAINT ck_challenge_result_dish_name CHECK (btrim(dish_name) <> '' AND char_length(dish_name) <= 200),
    CONSTRAINT ck_challenge_result_description CHECK (btrim(description) <> '' AND char_length(description) <= 4000),
    CONSTRAINT ck_challenge_result_evaluation CHECK (
        evaluation IS NULL OR (btrim(evaluation) <> '' AND char_length(evaluation) <= 4000)
    ),
    CONSTRAINT ck_challenge_result_version CHECK (version >= 0)
);

CREATE INDEX ix_challenge_result_challenge_created
    ON challenge_result (challenge_id, created_at, id);

CREATE INDEX ix_challenge_result_participant
    ON challenge_result (participant_id, challenge_id);

CREATE OR REPLACE FUNCTION maintain_challenge_result_identity()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.challenge_id <> OLD.challenge_id OR NEW.participant_id <> OLD.participant_id THEN
        RAISE EXCEPTION 'challenge result cannot move to another challenge or participant';
    END IF;
    IF NEW.created_at <> OLD.created_at THEN
        RAISE EXCEPTION 'challenge result creation timestamp is immutable';
    END IF;
    IF NEW.version <> OLD.version + 1 THEN
        RAISE EXCEPTION 'challenge result version must increase exactly once per update';
    END IF;
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_challenge_result_maintain_identity
BEFORE UPDATE
ON challenge_result
FOR EACH ROW
EXECUTE FUNCTION maintain_challenge_result_identity();

CREATE TABLE challenge_result_ingredient (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_result_id     bigint NOT NULL REFERENCES challenge_result(id) ON DELETE CASCADE,
    display_text            text NOT NULL,
    ingredient_concept_id   bigint REFERENCES ingredient_concept(id) ON DELETE RESTRICT,
    created_at              timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT ck_challenge_result_ingredient_display
        CHECK (btrim(display_text) <> '' AND char_length(display_text) <= 200)
);

CREATE UNIQUE INDEX uq_challenge_result_ingredient_display_ci
    ON challenge_result_ingredient (challenge_result_id, lower(btrim(display_text)));

CREATE INDEX ix_challenge_result_ingredient_concept
    ON challenge_result_ingredient (ingredient_concept_id)
    WHERE ingredient_concept_id IS NOT NULL;

CREATE OR REPLACE FUNCTION validate_challenge_result_ingredient_limit()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF (SELECT count(*) FROM challenge_result_ingredient
        WHERE challenge_result_id = NEW.challenge_result_id) >= 25 THEN
        RAISE EXCEPTION 'a challenge result may contain at most 25 own ingredients';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_challenge_result_ingredient_limit
BEFORE INSERT
ON challenge_result_ingredient
FOR EACH ROW
EXECUTE FUNCTION validate_challenge_result_ingredient_limit();

CREATE TABLE challenge_result_photo (
    challenge_result_id     bigint PRIMARY KEY REFERENCES challenge_result(id) ON DELETE CASCADE,
    content_bytes           bytea NOT NULL,
    content_type            text NOT NULL,
    original_filename       text NOT NULL,
    byte_size               bigint NOT NULL,
    width                   integer NOT NULL,
    height                  integer NOT NULL,
    sha256                  bytea NOT NULL,
    version                 bigint NOT NULL DEFAULT 0,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT ck_challenge_result_photo_content_type CHECK (content_type IN ('image/png', 'image/jpeg')),
    CONSTRAINT ck_challenge_result_photo_byte_size CHECK (byte_size > 0 AND byte_size <= 10485760),
    CONSTRAINT ck_challenge_result_photo_content_size CHECK (octet_length(content_bytes) = byte_size),
    CONSTRAINT ck_challenge_result_photo_filename CHECK (btrim(original_filename) <> ''),
    CONSTRAINT ck_challenge_result_photo_dimensions CHECK (
        width > 0 AND height > 0 AND width::bigint * height::bigint <= 50000000
    ),
    CONSTRAINT ck_challenge_result_photo_sha256_size CHECK (octet_length(sha256) = 32),
    CONSTRAINT ck_challenge_result_photo_version CHECK (version >= 0)
);

