     WHERE concept.id IS NULL;
    IF problem_codes IS NOT NULL THEN
        RAISE EXCEPTION 'Catalog draw-weight calibration is missing target codes: %', problem_codes;
    END IF;

    SELECT string_agg(concept.code || '=' || concept.base_draw_weight, ', ' ORDER BY concept.code)
      INTO problem_codes
      FROM ingredient_concept concept
      JOIN approved_catalog_draw_weight approved ON approved.code = concept.code
     WHERE concept.base_draw_weight NOT IN (approved.expected_weight, approved.target_weight);
    IF problem_codes IS NOT NULL THEN
        RAISE EXCEPTION 'Catalog draw-weight calibration found unexpected weight drift: %', problem_codes;
    END IF;

